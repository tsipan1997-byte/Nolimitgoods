const IS_EXCAVATOR = /excavator|digger/i;

export type LotWeight = { kg: number; approx: boolean };

export function lotWeight(lot: AuctionLot): LotWeight | null {
  const exact = EXACT[lot.item];
  if (exact) return { kg: exact, approx: false };
  if (!IS_EXCAVATOR.test(lot.original) && !/екскаватор/i.test(lot.title)) return null;
  for (const [re, kg] of MODEL) if (re.test(lot.original)) return { kg, approx: true };
  return null;
}

export function weightLabel(w: LotWeight): string {
  if (!w.approx) return `${w.kg.toLocaleString('uk-UA')} кг`;
  const t = (Math.round(w.kg / 100) / 10).toLocaleString('uk-UA');
  return `≈ ${t} т (за паспортом моделі)`;
}
